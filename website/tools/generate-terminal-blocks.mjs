import { execFileSync } from "node:child_process";
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const toolsDir = path.dirname(fileURLToPath(import.meta.url));
const websiteDir = path.resolve(toolsDir, "..");
const repoDir = path.resolve(websiteDir, "..");

function render(target) {
  return execFileSync(
    "gleam",
    ["run", "-m", "spruce_landing_demo", "--target", target],
    {
      cwd: repoDir,
      encoding: "utf8",
      env: { ...process.env, FORCE_COLOR: "3" },
    },
  );
}

const erlang = render("erlang");
const javascript = render("javascript");

if (erlang !== javascript) {
  throw new Error("Website demo output differs between Erlang and JavaScript");
}

const json = execFileSync(
  process.execPath,
  [path.join(toolsDir, "ansi2html.cjs")],
  { encoding: "utf8", input: erlang },
);
JSON.parse(json);

await writeFile(
  path.join(websiteDir, "src/data/terminalBlocks.ts"),
  `// AUTO-GENERATED by tools/generate-terminal-blocks.mjs. Do not edit.\n\nexport const terminalBlocks: Record<string, string> = ${json.trim()};\n`,
);
