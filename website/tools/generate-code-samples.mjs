import { readFile, writeFile } from "node:fs/promises";
import { ExpressiveCode, ExpressiveCodeTheme } from "expressive-code";
import { toHtml } from "expressive-code/hast";

const theme = new ExpressiveCodeTheme({
  name: "spruce",
  type: "dark",
  bg: "#090d0b",
  fg: "#cdd6d0",
  colors: {
    "editor.background": "#090d0b",
    "editor.foreground": "#cdd6d0",
    "editor.selectionBackground": "#3f9a6e55",
    "editorLineNumber.foreground": "#74877d",
    "focusBorder": "#4cb782",
    "scrollbarSlider.background": "#ffffff1f",
    "scrollbarSlider.hoverBackground": "#ffffff33",
  },
  tokenColors: [
    {
      scope: ["comment", "punctuation.definition.comment"],
      settings: { foreground: "#74877d", fontStyle: "italic" },
    },
    {
      scope: ["keyword", "storage.modifier", "storage.type"],
      settings: { foreground: "#ec6a82" },
    },
    {
      scope: ["string", "string.quoted"],
      settings: { foreground: "#58c98c" },
    },
    {
      scope: ["constant.numeric", "constant.language"],
      settings: { foreground: "#e6c46a" },
    },
    {
      scope: ["entity.name.function", "support.function"],
      settings: { foreground: "#6aa9e9" },
    },
    {
      scope: [
        "entity.name.namespace",
        "entity.name.type",
        "support.type",
        "variable.other.constant",
      ],
      settings: { foreground: "#56b3a4" },
    },
  ],
});

const engine = new ExpressiveCode({
  themes: [theme],
  frames: false,
  useDarkModeMediaQuery: false,
  styleOverrides: {
    borderRadius: "0",
    borderWidth: "0",
    codeBackground: "#090d0b",
    codeForeground: "#cdd6d0",
    codeFontFamily: "var(--font-mono)",
    codeFontSize: "0.82rem",
    codeLineHeight: "1.62",
    codePaddingBlock: "22px",
    codePaddingInline: "22px",
    focusBorder: "#4cb782",
    scrollbarThumbColor: "#ffffff1f",
    scrollbarThumbHoverColor: "#ffffff33",
    textMarkers: {
      markBackground: "#3f9a6e14",
      markBorderColor: "#3f9a6e",
    },
  },
});

const source = await readFile(
  new URL("../code-samples/main.gleam", import.meta.url),
  "utf8",
);
const result = await engine.render({
  code: source.trimEnd(),
  language: "gleam",
  meta: "mark={9-13}",
});

const html = toHtml(result.renderedGroupAst);
const styles = [
  await engine.getBaseStyles(),
  await engine.getThemeStyles(),
  ...(result.styles ?? []),
].join("\n");

await writeFile(
  new URL("../src/data/codeSamples.ts", import.meta.url),
  `// AUTO-GENERATED by tools/generate-code-samples.mjs. Do not edit.\n\nexport const codeSamples = {\n  main: ${JSON.stringify(html)},\n} as const;\n`,
);
await writeFile(
  new URL("../src/data/expressive-code.css", import.meta.url),
  `/* AUTO-GENERATED by tools/generate-code-samples.mjs. Do not edit. */\n${styles}\n`,
);
